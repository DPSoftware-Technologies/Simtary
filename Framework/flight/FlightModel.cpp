void Inertia (const HelicopterSpec& s, double out[3]) {
    for (int i = 0; i < 3; ++i) out[i] = s.inertia[i];
    if (out[0] > 0 && out[1] > 0 && out[2] > 0) return;
    // Half a uniform box: real fuselages carry their mass near the middle.
    const double m = s.emptyMass, l = s.length, w = s.width, h = s.height;
    const double roll = 0.5 * m / 12.0 * (w * w + h * h);
    const double pitch = 0.5 * m / 12.0 * (l * l + h * h);
    const double yaw = 0.5 * m / 12.0 * (l * l + w * w);
    if (out[0] <= 0) out[0] = roll;
    if (out[1] <= 0) out[1] = pitch;
    if (out[2] <= 0) out[2] = yaw;
}

bool WriteJSBSimModel (const HelicopterSpec& s, const std::string& root, const std::string& model, std::string* error) {
    namespace fs = std::filesystem;
    std::error_code ec;
    const fs::path aircraftDir = fs::path(root) / "aircraft" / model;
    const fs::path engineDir = fs::path(root) / "engine";
    fs::create_directories(aircraftDir, ec);
    fs::create_directories(engineDir, ec);

    const std::string mainMotor = model + "_main_motor", tailMotor = model + "_tail_motor";
    const std::string mainRotor = model + "_main_rotor", tailRotor = model + "_tail_rotor";
    const double mainGear = s.engine.engineRpm / s.mainRotor.nominalRpm;
    // The tail rotor is linked to the main one: its gear ratio is engine rpm / tail rpm.
    const double tailGear = s.engine.engineRpm / s.tailRotor.nominalRpm;

    if (!WriteFile(engineDir / (mainMotor + ".xml"),
                   "<?xml version=\"1.0\"?>\n<electric_engine name=\"" + mainMotor + "\">\n  <power unit=\"HP\">" +
                   Num(s.engine.maxPowerKW * kHpPerKW) + "</power>\n</electric_engine>\n", error)) return false;
    if (!WriteFile(engineDir / (tailMotor + ".xml"),
                   "<?xml version=\"1.0\"?>\n<electric_engine name=\"" + tailMotor + "\">\n  <power unit=\"HP\">1</power>\n</electric_engine>\n",
                   error)) return false;
    if (!WriteFile(engineDir / (mainRotor + ".xml"), RotorXml(mainRotor, s.mainRotor, mainGear, false), error)) return false;
    if (!WriteFile(engineDir / (tailRotor + ".xml"), RotorXml(tailRotor, s.tailRotor, tailGear, true), error)) return false;

    double I[3];
    Inertia(s, I);
    const double weightLbs = s.emptyMass * kLbsPerKg;
    const Station cg = ToStructure(s.cg);
    const Station hub = ToStructure(s.mainRotor.hub);
    const Station tailHub = ToStructure(s.tailRotor.hub);
    const double tailArmFt = s.tailArm * kFtPerM;
    const double finFt2 = s.finArea * kFt2PerM2, stabFt2 = s.stabilizerArea * kFt2PerM2;

    std::ostringstream o;
    o << "<?xml version=\"1.0\"?>\n<!-- generated by Simtary (Framework/flight) from a HelicopterSpec - do not edit -->\n"
      << "<fdm_config name=\"" << model << "\" version=\"2.0\" release=\"ALPHA\">\n"
      << "  <fileheader><author>Simtary</author><description>" << s.name << "</description></fileheader>\n\n"
      << "  <metrics>\n"
      << "    <wingarea unit=\"FT2\">1</wingarea>\n    <wingspan unit=\"FT\">1</wingspan>\n    <chord unit=\"FT\">1</chord>\n"
      << "    <htailarea unit=\"FT2\">" << Num(stabFt2) << "</htailarea>\n    <htailarm unit=\"FT\">" << Num(tailArmFt) << "</htailarm>\n"
      << "    <vtailarea unit=\"FT2\">" << Num(finFt2) << "</vtailarea>\n    <vtailarm unit=\"FT\">" << Num(tailArmFt) << "</vtailarm>\n"
      << Location("AERORP", cg, "    ") << Location("EYEPOINT", cg, "    ") << Location("VRP", ToStructure(s.cg), "    ")
      << "  </metrics>\n\n";

    o << "  <mass_balance>\n"
      << "    <ixx unit=\"SLUG*FT2\">" << Num(I[0] * kSlugFt2PerKgM2) << "</ixx>\n"
      << "    <iyy unit=\"SLUG*FT2\">" << Num(I[1] * kSlugFt2PerKgM2) << "</iyy>\n"
      << "    <izz unit=\"SLUG*FT2\">" << Num(I[2] * kSlugFt2PerKgM2) << "</izz>\n"
      << "    <emptywt unit=\"LBS\">" << Num(weightLbs) << "</emptywt>\n"
      << Location("CG", cg, "    ") << "  </mass_balance>\n\n";

    // Skids: a contact at each rail end, sprung to ~8 cm under the weight and close to
    //	critically damped; the tail boom, the nose and the rotor are hard structure.
    const double spring = 3.0 * weightLbs, damping = 0.3 * weightLbs;
    auto bogey = [&](const char* name, double x, double z) {
        const double p[3] = { x, 0.0, z };
        o << "    <contact type=\"BOGEY\" name=\"" << name << "\">\n" << Location(nullptr, ToStructure(p), "      ")
          << "      <static_friction>0.8</static_friction><dynamic_friction>0.6</dynamic_friction><rolling_friction>0.6</rolling_friction>\n"
          << "      <spring_coeff unit=\"LBS/FT\">" << Num(spring) << "</spring_coeff>\n"
          << "      <damping_coeff unit=\"LBS/FT/SEC\">" << Num(damping) << "</damping_coeff>\n"
          << "      <max_steer unit=\"DEG\">0</max_steer><brake_group>NONE</brake_group><retractable>0</retractable>\n    </contact>\n";
    };
    auto structure = [&](const char* name, double y, double z) {
        const double p[3] = { 0.0, y, z };
        o << "    <contact type=\"STRUCTURE\" name=\"" << name << "\">\n" << Location(nullptr, ToStructure(p), "      ")
          << "      <static_friction>1</static_friction><dynamic_friction>1</dynamic_friction>\n"
          << "      <spring_coeff unit=\"LBS/FT\">" << Num(spring * 2) << "</spring_coeff>\n"
          << "      <damping_coeff unit=\"LBS/FT/SEC\">" << Num(damping * 2) << "</damping_coeff>\n    </contact>\n";
    };
    o << "  <ground_reactions>\n";
    bogey("skid_front_left", -s.skidHalfWidth, s.skidFront);
    bogey("skid_front_right", s.skidHalfWidth, s.skidFront);
    bogey("skid_rear_left", -s.skidHalfWidth, s.skidBack);
    bogey("skid_rear_right", s.skidHalfWidth, s.skidBack);
    structure("tail", s.tailRotor.hub[1] * 0.5, s.tailRotor.hub[2]);
    structure("nose", s.height * 0.3, s.length * 0.45);
    structure("rotor", s.mainRotor.hub[1] + 0.3, 0.0);
    o << "  </ground_reactions>\n\n";

    o << "  <propulsion>\n"
      << "    <engine file=\"" << mainMotor << "\">\n"
      << "      <thruster file=\"" << mainRotor << "\">\n" << Location(nullptr, hub, "        ")
      << "        <orient unit=\"DEG\"><roll>0</roll><pitch>90</pitch><yaw>0</yaw></orient>\n"
      << "        <sense>" << s.mainRotor.sense << "</sense>\n      </thruster>\n    </engine>\n"
      << "    <engine file=\"" << tailMotor << "\">\n"
      << "      <thruster file=\"" << tailRotor << "\">\n" << Location(nullptr, tailHub, "        ")
      << "        <orient unit=\"DEG\"><roll>0</roll><pitch>0</pitch><yaw>90</yaw></orient>\n"
      << "        <sense>" << s.tailRotor.sense << "</sense>\n      </thruster>\n    </engine>\n"
      << "  </propulsion>\n\n";

    // Fuselage drag by direction, a side force against sideslip, and the fin / stabiliser
    //	weathervaning the nose into the wind with rate damping (lift slope ~3 /rad, low-aspect).
    const double finK = finFt2 * tailArmFt * 3.0, stabK = stabFt2 * tailArmFt * 3.0;
    o << "  <aerodynamics>\n"
      << "    <axis name=\"DRAG\">\n"
      << Term("drag-front", s.dragAreaFront * kFt2PerM2, "")
      << Term("drag-side", s.dragAreaSide * kFt2PerM2, "          <sin><property>aero/beta-rad</property></sin>\n          <sin><property>aero/beta-rad</property></sin>\n")
      << Term("drag-top", s.dragAreaTop * kFt2PerM2, "          <sin><property>aero/alpha-rad</property></sin>\n          <sin><property>aero/alpha-rad</property></sin>\n")
      << "    </axis>\n"
      << "    <axis name=\"SIDE\">\n"
      << Term("side-force", -s.dragAreaSide * kFt2PerM2, "          <sin><property>aero/beta-rad</property></sin>\n")
      << "    </axis>\n"
      << "    <axis name=\"YAW\">\n"
      << Term("yaw-fin", finK, "          <property>aero/beta-rad</property>\n")
      << "      <function name=\"aero/yaw-damping\">\n        <product>\n          <value>" << Num(-0.5 * finFt2 * tailArmFt * tailArmFt * 3.0) << "</value>\n"
      << "          <property>atmosphere/rho-slugs_ft3</property>\n          <property>velocities/vt-fps</property>\n"
      << "          <property>velocities/r-aero-rad_sec</property>\n        </product>\n      </function>\n"
      << "    </axis>\n"
      << "    <axis name=\"PITCH\">\n"
      << Term("pitch-stabilizer", -stabK, "          <property>aero/alpha-rad</property>\n")
      << "      <function name=\"aero/pitch-damping\">\n        <product>\n          <value>" << Num(-0.5 * stabFt2 * tailArmFt * tailArmFt * 3.0) << "</value>\n"
      << "          <property>atmosphere/rho-slugs_ft3</property>\n          <property>velocities/vt-fps</property>\n"
      << "          <property>velocities/q-aero-rad_sec</property>\n        </product>\n      </function>\n"
      << "    </axis>\n"
      << "  </aerodynamics>\n\n</fdm_config>\n";

    return WriteFile(aircraftDir / (model + ".xml"), o.str(), error);
}

