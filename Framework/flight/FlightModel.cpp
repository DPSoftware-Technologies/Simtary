        s.length = 9.5; s.width = 1.9; s.height = 2.9;
        s.cg[0] = 0; s.cg[1] = 1.3; s.cg[2] = 0.1;
        s.dragAreaFront = 0.9; s.dragAreaSide = 5.0; s.dragAreaTop = 7.0;
        s.finArea = 0.6; s.stabilizerArea = 0.5; s.tailArm = 5.6;
        s.mainRotor.diameter = 10.16; s.mainRotor.blades = 2; s.mainRotor.chord = 0.33;
        s.mainRotor.nominalRpm = 394; s.mainRotor.twistDeg = -10; s.mainRotor.bladeMass = 38;   // blade mass estimated
        s.mainRotor.hub[1] = 2.9;
        s.tailRotor.diameter = 1.65; s.tailRotor.blades = 2; s.tailRotor.chord = 0.12;
        s.tailRotor.nominalRpm = 2550; s.tailRotor.twistDeg = 0; s.tailRotor.bladeMass = 1.5;
        s.tailRotor.hub[0] = 0.3; s.tailRotor.hub[1] = 1.4; s.tailRotor.hub[2] = -6.2;
