constexpr double kLbsPerKg = 2.20462262;
constexpr double kInPerM = 39.3700787;
constexpr double kFtPerM = 3.28083990;
constexpr double kSlugFt2PerKgM2 = 0.737562149;
constexpr double kSlugPerKg = 0.0685217659;
constexpr double kHpPerKW = 1.34102209;
constexpr double kFt2PerM2 = 10.7639104;
constexpr double kPi = 3.14159265358979;

// Structural frame: X aft, Y right, Z up, inches. The +400 in keeps every station positive.
struct Station { double x, y, z; };
Station ToStructure (const double p[3]) {
    return { 400.0 - p[2] * kInPerM, p[0] * kInPerM, p[1] * kInPerM };
}

std::string Num (double v) {
    char buf[64];
    std::snprintf(buf, sizeof(buf), "%.6g", v);
    return buf;
}

std::string Location (const char* name, const Station& s, const char* indent) {
    std::ostringstream o;
    o << indent << "<location" << (name ? std::string(" name=\"") + name + "\"" : std::string()) << " unit=\"IN\">"
      << "<x>" << Num(s.x) << "</x><y>" << Num(s.y) << "</y><z>" << Num(s.z) << "</z></location>\n";
    return o.str();
}

std::string RotorXml (const std::string& name, const RotorSpec& r, double gearRatio, bool tail) {
    const double radiusFt = r.diameter * 0.5 * kFtPerM;
    const double bladeSlug = r.bladeMass * kSlugPerKg;
    const double flapping = bladeSlug * radiusFt * radiusFt / 3.0;   // uniform blade about the hub
    std::ostringstream o;
    o << "<?xml version=\"1.0\"?>\n<!-- generated by Simtary (Framework/flight) - do not edit -->\n"
      << "<rotor name=\"" << name << "\">\n"
      << "  <diameter unit=\"FT\">" << Num(r.diameter * kFtPerM) << "</diameter>\n"
      << "  <numblades>" << r.blades << "</numblades>\n"
      << "  <gearratio>" << Num(gearRatio) << "</gearratio>\n"
      << "  <nominalrpm>" << Num(r.nominalRpm) << "</nominalrpm>\n"
      << "  <chord unit=\"FT\">" << Num(r.chord * kFtPerM) << "</chord>\n"
      << "  <liftcurveslope>" << Num(r.liftCurveSlope) << "</liftcurveslope>\n"
      << "  <flappingmoment unit=\"SLUG*FT2\">" << Num(flapping) << "</flappingmoment>\n"
      << "  <twist>" << Num(r.twistDeg * kPi / 180.0) << "</twist>\n"
      << "  <massmoment>" << Num(bladeSlug * radiusFt * 0.5) << "</massmoment>\n"
      << "  <tiplossfactor>" << Num(r.tipLoss) << "</tiplossfactor>\n"
      << "  <polarmoment unit=\"SLUG*FT2\">" << Num(flapping * r.blades) << "</polarmoment>\n"
      << "  <inflowlag>" << Num(r.inflowLag) << "</inflowlag>\n"
      << "  <hingeoffset unit=\"FT\">" << Num(r.hingeOffset * radiusFt) << "</hingeoffset>\n";
    if (tail) {
        o << "  <ExternalRPM> 0 </ExternalRPM>\n  <controlmap> TAIL </controlmap>\n";
    } else if (r.groundEffectExp > 0) {
        o << "  <groundeffectexp>" << Num(r.groundEffectExp) << "</groundeffectexp>\n"
          << "  <groundeffectshift unit=\"FT\">" << Num(r.hub[1] * kFtPerM) << "</groundeffectshift>\n";
    }
    o << "</rotor>\n";
    return o.str();
}

bool WriteFile (const std::filesystem::path& p, const std::string& text, std::string* error) {
    std::ofstream f(p, std::ios::binary | std::ios::trunc);
    if (!f) {
        if (error) *error = "cannot write " + p.generic_string();
        return false;
    }
    f << text;
    return bool(f);
}

// A <function> computing qbar * area * term, for the aerodynamics axes.
std::string Term (const std::string& name, double areaFt2, const std::string& inner) {
    return "      <function name=\"aero/" + name + "\">\n        <product>\n          <property>aero/qbar-psf</property>\n"
           "          <value>" + Num(areaFt2) + "</value>\n" + inner + "        </product>\n      </function>\n";
}

