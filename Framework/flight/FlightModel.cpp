        s.tailRotor.hub[0] = 0.4; s.tailRotor.hub[1] = 2.1; s.tailRotor.hub[2] = -8.6;
        s.engine.maxPowerKW = 1040;
        s.skidHalfWidth = 1.3; s.skidFront = 1.8; s.skidBack = -1.6;
